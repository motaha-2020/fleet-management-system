/** Every beat, in play order, with its chapter and part. */
export function allBeats() {
  return CHAPTERS.flatMap((c) => c.parts.flatMap((p) => p.beats.map((b) => ({ ...b, chapter: c.id, part: p.key, type: p.type }))));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = process.argv[2] ?? "training-out";
  fs.mkdirSync(out, { recursive: true });
  const beats = allBeats();
  const ids = new Set();
  for (const b of beats) { if (ids.has(b.id)) throw new Error(`duplicate beat ${b.id}`); ids.add(b.id); }
  fs.writeFileSync(path.join(out, "script.json"), JSON.stringify({ voice: VOICE, rate: RATE, beats: beats.map(({ id, text }) => ({ id, text })) }, null, 2));
  const md = ["# سكريبت الفيديو التدريبي — منصة الأسطول", "", `الصوت: ${VOICE} · ${beats.length} مقطع`, ""];
  for (const c of CHAPTERS) {
    md.push(`## ${c.id} · ${c.title}`, "");
    for (const p of c.parts) {
      md.push(p.type === "card" ? `**شريحة:** ${p.card.title ?? p.card.kicker}` : `**تسجيل حي (${p.kind === "phone" ? "موبايل" : "كمبيوتر"}):** ${p.key}`, "");
      for (const b of p.beats) md.push(`- \`${b.id}\` ${b.text}`);
      md.push("");
    }
  }
  fs.writeFileSync(path.join(out, "script.md"), md.join("\n"));
  const words = beats.reduce((n, b) => n + b.text.split(/\s+/).length, 0);
  console.log(`${beats.length} beats, ${words} words → ${out}/script.json, script.md`);
}
